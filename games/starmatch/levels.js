/** 第 n 关（从 1 开始）。打完表以后在后 20 关里循环，颜色换一套 */
export function levelSpec(n) {
  const i = n <= TABLE.length ? n - 1 : TABLE.length - 20 + ((n - TABLE.length - 1) % 20);
  const [pattern, colorCount, want, tip] = TABLE[i];
  // 每关换一个颜色起点，不要老是收集粉色
  const shift = n <= 3 ? 0 : (n * 2) % 6;
  const palette = Array.from({ length: colorCount }, (_, k) => (k + shift) % 6);
  const size = C * R;
  const ice = new Array(size).fill(0), lock = new Array(size).fill(0);
  let iceCells = 0, lockCells = 0;
  if (pattern) {
    P[pattern].forEach((row, r) => [...row].forEach((ch, c) => {
      const at = r * C + c;
      if (ch === '1' || ch === 'M') { ice[at] = 1; iceCells++; }
      if (ch === '2') { ice[at] = 2; iceCells++; }
      if (ch === 'L' || ch === 'M') { lock[at] = 1; lockCells++; }
    }));
  }
  const goals = want.map(([k, need]) => ({ type: 'color', c: palette[k % palette.length], need }));
  if (iceCells) goals.push({ type: 'ice', need: iceCells });
  if (lockCells) goals.push({ type: 'lock', need: lockCells });
  return { n, C, R, colors: palette, moves: MOVES[i] ?? 45, goals, ice, lock, tip: tip || '' };
}
